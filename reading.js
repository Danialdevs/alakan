export function hashString(text) {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function rng(seed) {
  let s = seed >>> 0 || 1;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

/**
 * features: { z: number[6] (rough z-scores per trait, may be empty), key: string (stable fingerprint), hand }
 */
export function makeReading(features) {
  const seed = hashString(features.key || String(Math.random()));
  const rand = rng(seed);
  const z = features.z && features.z.length === 6 ? features.z : TRAITS.map(() => 0);
  const scores = TRAITS.map((_, i) => {
    const v = 70 + 13 * clamp(z[i], -2, 2) + (rand() - 0.5) * 22;
    return Math.round(clamp(v, 41, 98));
  });

  const centered = scores.map((s) => s - 70);
  let best = ARCHETYPES[0];
  let bestScore = -Infinity;
  for (const a of ARCHETYPES) {
    const norm = Math.hypot(...a.w);
    const score = a.w.reduce((sum, w, i) => sum + w * centered[i], 0) / norm + rand() * 2;
    if (score > bestScore) {
      bestScore = score;
      best = a;
    }
  }

  const [, , crea, emp, logic, energy] = scores;
  const level = (v) => (v >= 78 ? 'high' : v >= 62 ? 'mid' : 'low');
  const lines = {
    life: LINES.life[level(energy)],
    heart: LINES.heart[level(emp)],
    head: Math.abs(logic - crea) < 8 ? LINES.head.both : logic > crea ? LINES.head.logic : LINES.head.crea,
  };

  return { seed, archetype: best, scores, lines, hand: features.hand || 0 };
}

export function localized(reading, lang) {
  const a = reading.archetype[lang];
  return {
    title: a.title,
    desc: a.desc,
    advice: a.advice,
    hue: reading.archetype.hue,
    traits: TRAITS.map((t, i) => ({ name: t[lang], value: reading.scores[i] })),
    lines: Object.fromEntries(Object.entries(reading.lines).map(([k, v]) => [k, v[lang]])),
  };
}
