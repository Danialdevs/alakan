// Minimal static server: node serve.mjs [port]. Camera access needs http://localhost or https.
import { createServer } from 'node:http';
import { readFile, stat } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
const port = Number(process.argv[2] || process.env.PORT || 8080);
const types = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css',
  '.json': 'application/json', '.wasm': 'application/wasm', '.svg': 'image/svg+xml', '.png': 'image/png',
  '.task': 'application/octet-stream',
};

createServer(async (req, res) => {
  const path = decodeURIComponent(new URL(req.url, 'http://x').pathname);
  let file = normalize(join(root, path));
  if (!file.startsWith(root)) return res.writeHead(403).end();
  try {
    if ((await stat(file)).isDirectory()) file = join(file, 'index.html');
    const body = await readFile(file);
    res.writeHead(200, { 'content-type': types[extname(file)] || 'application/octet-stream', 'cache-control': 'no-cache' });
    res.end(body);
  } catch {
    res.writeHead(404).end('not found');
  }
})
  .on('error', (error) => {
    if (error.code !== 'EADDRINUSE') throw error;
    console.log(`Port ${port} is already in use — Alakan is probably already running: http://localhost:${port}`);
    console.log(`To use another port: node serve.mjs ${port + 1}`);
    process.exit(0);
  })
  .listen(port, '127.0.0.1', () => console.log(`Alakan: http://localhost:${port}`));
